//! `rusm new <name> --template todo-board --lang ts|rust|go` — scaffold the full
//! collaborative todo board (HTTP CRUD + a live SSE feed + WebSocket chat + a service
//! driven by a worker), the same app the `examples/<lang>/` directories hold.
//!
//! **Single source of truth, with a vendored copy.** The scaffold contents ARE the real
//! example files — but `cargo publish` only packages files *inside* this crate, so the
//! curated example tree is vendored under `rusm-cli/templates/<lang>/` and embedded from
//! there with `include_str!` (embedding straight from `../examples/` would compile in-repo
//! but break the published crate, where `examples/` isn't in the tarball). `templates/` is
//! a verbatim copy of the curated `examples/<lang>` files, regenerated by `make
//! sync-templates`; two tests guard it — the embedded set must match the on-disk example,
//! and each vendored file must be byte-identical to its `examples/` original — so the copy
//! can never silently drift. The one thing a standalone scaffolded app must differ in is
//! its dependency manifests: the examples use repo-local path/`replace` deps (they live in
//! this tree), so those are rewritten to published references on the way out.

use anyhow::{bail, Result};
use std::path::PathBuf;

use crate::scaffold::{package_json, Lang, SDK_VERSION};

/// The template to scaffold. `TodoBoard` is the full multi-protocol app; `Weather` is the
/// custom-bridge example (a native `weather` host function called from the guest); `Mailer`
/// is a TS-hosted bridge that sends transactional email via Resend. The `Weather` and
/// `Mailer` files come from the bridge scaffolder (`crate::scaffold::bridge_files` /
/// `mailer_bridge_files`), not this module, so neither is listed in `files()` below.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Template {
    TodoBoard,
    Weather,
    Mailer,
}

/// Parse the `--template` value.
pub fn parse_template(value: &str) -> Result<Template> {
    match value {
        "todo-board" | "todo" | "board" => Ok(Template::TodoBoard),
        "weather" | "bridge" | "custom-bridge" => Ok(Template::Weather),
        "mailer" | "email" => Ok(Template::Mailer),
        other => bail!(
            "unknown template `{other}` — templates are `todo-board`, `weather`, and `mailer`"
        ),
    }
}

/// `(relative path within the app, file contents)` for one example file, embedded from the
/// vendored `rusm-cli/templates/<lang>/<path>` copy at build time (kept identical to
/// `examples/<lang>/<path>` by `make sync-templates` and the guard tests below).
macro_rules! embed {
    ($lang:literal, $($path:literal),+ $(,)?) => {
        &[ $( ($path, include_str!(concat!("../templates/", $lang, "/", $path))) ),+ ]
    };
}

type Files = &'static [(&'static str, &'static str)];

